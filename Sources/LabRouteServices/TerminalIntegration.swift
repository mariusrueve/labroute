import Foundation
import Darwin
import LabRouteCore

/// Files LabRoute reads or writes for terminal integration. Fixtures point all
/// of them into the fixture root, so tests never touch the real ~/.ssh or ~/.zshrc.
public struct TerminalFiles: Sendable {
    public var userSSHConfig: URL
    public var managedSSHConfig: URL
    public var zshrc: URL
    public var labroutePath: String
    public init(userSSHConfig: URL, managedSSHConfig: URL, zshrc: URL, labroutePath: String) {
        self.userSSHConfig = userSSHConfig; self.managedSSHConfig = managedSSHConfig; self.zshrc = zshrc; self.labroutePath = labroutePath
    }
    public static func live() -> Self {
        let home = FileManager.default.homeDirectoryForCurrentUser
        return Self(userSSHConfig: home.appendingPathComponent(".ssh/config"),
                    managedSSHConfig: home.appendingPathComponent(".ssh/labroute/config"),
                    zshrc: home.appendingPathComponent(".zshrc"),
                    labroutePath: Bundle.main.bundleURL.appendingPathComponent("Contents/MacOS/labroute").path)
    }
    public static func fixture(root: URL) -> Self {
        Self(userSSHConfig: root.appendingPathComponent("home/.ssh/config"),
             managedSSHConfig: root.appendingPathComponent("home/.ssh/labroute/config"),
             zshrc: root.appendingPathComponent("home/.zshrc"), labroutePath: "/usr/local/bin/labroute")
    }

    public var includeLine: String {
        let home = FileManager.default.homeDirectoryForCurrentUser.path
        let path = managedSSHConfig.path
        return "Include " + (path.hasPrefix(home + "/") ? "~" + path.dropFirst(home.count) : "\"" + path + "\"")
    }
    /// Re-evaluated before every prompt, so quitting or starting LabRoute takes
    /// effect in open shells. An `if`, so a missing app leaves exit status 0.
    public var shellLine: String {
        "if [ -x '\(labroutePath)' ]; then _labroute_env() { eval \"$('\(labroutePath)' env)\"; }; autoload -Uz add-zsh-hook; add-zsh-hook precmd _labroute_env; fi"
    }
    /// Earlier forms that set the variables only once, at shell start.
    public var legacyShellLines: [String] {
        ["if [ -x '\(labroutePath)' ]; then eval \"$('\(labroutePath)' env)\"; fi",
         "[ -x '\(labroutePath)' ] && eval \"$('\(labroutePath)' env)\""]
    }
}

public enum SSHConfigWriter {
    /// Writes only when the content changed. Never replaces a file LabRoute did not generate.
    @discardableResult
    public static func write(_ text: String, to url: URL, verify: (URL) async throws -> Void) async throws -> Bool {
        let existing = try? String(contentsOf: url, encoding: .utf8)
        if let existing {
            guard existing.hasPrefix(SSHConfigGenerator.header) else {
                throw RuntimeError.message("\(url.path) exists and was not generated by LabRoute. Move it away to let LabRoute manage it.")
            }
            if existing == text { return false }
        }
        let candidate = url.deletingLastPathComponent().appendingPathComponent(".config.candidate")
        try PrivateFile.write(Data(text.utf8), to: candidate)
        defer { try? FileManager.default.removeItem(at: candidate) }
        try await verify(candidate)
        try PrivateFile.write(Data(text.utf8), to: url)
        return true
    }

    /// Checks the candidate with OpenSSH's own parser for every alias.
    public static func verifyWithSSH(aliases: [String]) -> (URL) async throws -> Void {
        { candidate in
            for alias in aliases {
                let result = try await collect(ProcessSpec("/usr/bin/ssh", ["-G", "-F", candidate.path, "--", alias]),
                                               runner: SystemProcessRunner(), timeout: .seconds(10))
                guard result.0 == 0 else {
                    let detail = result.2.split(separator: "\n").first.map(String.init) ?? "ssh rejected the configuration"
                    throw RuntimeError.message("ssh rejected the generated configuration: " + detail)
                }
            }
        }
    }
}

public enum HookState: String, Sendable {
    case installed, missing, misplaced, outdated, symlink
}

/// The single lines that connect the user's own files to LabRoute.
public enum HookLines {
    public static let marker = "# Added by LabRoute"

    public static func state(of url: URL, line: String, legacy: [String] = [], mustPrecedeHosts: Bool) -> HookState {
        if isSymlink(url) { return .symlink }
        guard let text = try? String(contentsOf: url, encoding: .utf8) else { return .missing }
        var seenHost = false
        for raw in text.components(separatedBy: "\n") {
            let trimmed = raw.trimmingCharacters(in: .whitespaces)
            if trimmed == line { return mustPrecedeHosts && seenHost ? .misplaced : .installed }
            if legacy.contains(trimmed) { return .outdated }
            let keyword = trimmed.split(whereSeparator: { $0 == " " || $0 == "\t" || $0 == "=" }).first?.lowercased()
            if keyword == "host" || keyword == "match" { seenHost = true }
        }
        return .missing
    }

    /// Prepends (ssh, which uses the first value it finds) or appends (shell) the line, after a backup.
    public static func add(_ line: String, to url: URL, prepend: Bool, replacing legacy: [String] = []) throws {
        guard !isSymlink(url) else { throw RuntimeError.message("\(url.path) is a symbolic link. Add this line yourself: \(line)") }
        let existing = (try? String(contentsOf: url, encoding: .utf8)) ?? ""
        let mode = permissions(url) ?? 0o600
        if FileManager.default.fileExists(atPath: url.path) {
            let backup = URL(fileURLWithPath: url.path + ".labroute-backup")
            try? FileManager.default.removeItem(at: backup)
            try FileManager.default.copyItem(at: url, to: backup)
        }
        let cleaned = ([line] + legacy).reduce(existing) { removing($1, from: $0) }
        let block = marker + "\n" + line + "\n"
        let updated: String
        if prepend { updated = block + (cleaned.isEmpty ? "" : "\n" + cleaned) }
        else { updated = cleaned + (cleaned.isEmpty || cleaned.hasSuffix("\n") ? "" : "\n") + (cleaned.isEmpty ? "" : "\n") + block }
        try PrivateFile.write(Data(updated.utf8), to: url)
        chmod(url.path, mode)
    }

    public static func remove(_ line: String, from url: URL, legacy: [String] = []) throws {
        guard !isSymlink(url), let existing = try? String(contentsOf: url, encoding: .utf8) else { return }
        let updated = ([line] + legacy).reduce(existing) { removing($1, from: $0) }
        guard updated != existing else { return }
        let mode = permissions(url) ?? 0o600
        try PrivateFile.write(Data(updated.utf8), to: url)
        chmod(url.path, mode)
    }

    /// Drops the exact line and the marker directly above it, plus one blank line LabRoute added.
    static func removing(_ line: String, from text: String) -> String {
        var lines = text.components(separatedBy: "\n")
        while let index = lines.firstIndex(where: { $0.trimmingCharacters(in: .whitespaces) == line }) {
            var start = index, end = index + 1
            if start > 0 && lines[start - 1] == marker { start -= 1 }
            if start == 0, end < lines.count, lines[end].isEmpty, end + 1 < lines.count { end += 1 }
            else if start > 0, lines[start - 1].isEmpty { start -= 1 }
            lines.removeSubrange(start..<end)
        }
        return lines.joined(separator: "\n")
    }

    static func isSymlink(_ url: URL) -> Bool {
        var info = stat()
        return lstat(url.path, &info) == 0 && info.st_mode & S_IFMT == S_IFLNK
    }
    static func permissions(_ url: URL) -> mode_t? {
        var info = stat()
        return stat(url.path, &info) == 0 ? info.st_mode & 0o7777 : nil
    }
}
